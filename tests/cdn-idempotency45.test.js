import test from 'node:test';
import assert from 'node:assert/strict';
import os from 'node:os';
import fs from 'node:fs';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
const root=path.resolve(import.meta.dirname,'..');
const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'sa-idempotency45-'));
process.env.DB_PATH=path.join(tmp,'db.sqlite');process.env.PRIVATE_PATH=path.join(tmp,'private');process.env.NODE_ENV='test';
const {run,now}=await import('../src/database.js');
const {queueVideoRevocation,pendingRevocations}=await import('../src/media-revocation.js');
const id=Number(run('INSERT INTO users(email,name,created_at) VALUES(?,?,?)','idempotency45@example.test','Uploader',now()).lastInsertRowid);
const uploadId='cbbbbbbb-bbbb-4bbb-bbbb-bbbbbbbbbbbb';
run('INSERT INTO upload_sessions(id,user_id,video_id,original_filename,declared_type,expected_bytes,status,created_at,updated_at) VALUES(?,?,?,?,?,?,?,?,?)',uploadId,id,1,'fixture.mp4','video/mp4',2345,'PUBLISHED',now(),now());
queueVideoRevocation(1,'SAFETY_HOLD');
const dump=path.join(tmp,'aws-args');const fake=path.join(tmp,'aws');
fs.writeFileSync(fake,`#!/bin/sh\nprintf '%s\\n' "$@" > "$SA_MOCK_AWS_ARGS"\nprintf '{"Invalidation":{"Id":"I1234567890"}}\\n'\n`,{mode:0o700});
const cli=(env={})=>spawnSync(process.execPath,['scripts/request-cdn-invalidations.js'],{cwd:root,encoding:'utf8',env:{...process.env,SA_MOCK_AWS_ARGS:dump,SA_AWS_CLI_PATH:fake,SA_AWS_INVALIDATION_ACK:'YES',SA_CLOUDFRONT_DISTRIBUTION_ID:'E12345678901',...env},timeout:4000});
test('E05: invalidation batch uses stable caller id with a single bounded path',()=>{
 const first=cli();assert.equal(first.status,0,first.stderr);
 const args=fs.readFileSync(dump,'utf8').trim().split('\n');
 assert.ok(args.includes('--invalidation-batch'));
 assert.ok(!args.includes('--paths'));
 const batch=JSON.parse(args[args.indexOf('--invalidation-batch')+1]);
 assert.deepEqual(batch.Paths,{Quantity:1,Items:[`/media/${uploadId}/*`]});
 assert.match(batch.CallerReference,/^sa-[a-f0-9]{64}$/);
 assert.equal(pendingRevocations().length,0);
 const duplicate=cli();assert.equal(duplicate.status,0);assert.equal(JSON.parse(duplicate.stdout).requested,0);
});
