BEGIN;
ALTER TABLE upload_sessions ADD COLUMN IF NOT EXISTS planned_release_at TIMESTAMPTZ;
ALTER TABLE upload_sessions ADD COLUMN IF NOT EXISTS selected_poster TEXT NOT NULL DEFAULT 'poster.jpg';
CREATE TABLE IF NOT EXISTS processing_dead_letters (
 upload_id UUID PRIMARY KEY REFERENCES upload_sessions(id) ON DELETE CASCADE,
 attempt_count INTEGER NOT NULL CHECK(attempt_count>=1),failure_reason TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS creator_collaborators (
 owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 collaborator_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 role TEXT NOT NULL CHECK(role IN ('ANALYST','EDITOR','UPLOADER')),
 status TEXT NOT NULL DEFAULT 'INVITED' CHECK(status IN ('INVITED','ACCEPTED','REVOKED')),
 invited_at TIMESTAMPTZ NOT NULL,accepted_at TIMESTAMPTZ,
 PRIMARY KEY(owner_id,collaborator_id),CHECK(owner_id<>collaborator_id)
);
CREATE INDEX IF NOT EXISTS ix_pg_creator_collab_invitee ON creator_collaborators(collaborator_id,status);
CREATE TABLE IF NOT EXISTS license_review_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 upload_id UUID NOT NULL REFERENCES upload_sessions(id),actor_id BIGINT NOT NULL REFERENCES users(id),
 action TEXT NOT NULL,note TEXT NOT NULL,created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_pg_license_review_events_upload ON license_review_events(upload_id,id DESC);
CREATE TABLE IF NOT EXISTS compliance_case_evidence_refs (
 case_id BIGINT NOT NULL REFERENCES compliance_cases(id) ON DELETE CASCADE,
 submitted_by BIGINT NOT NULL REFERENCES users(id),reference TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL,PRIMARY KEY(case_id,reference)
);
CREATE TABLE IF NOT EXISTS compliance_review_signoffs (
 case_id BIGINT NOT NULL REFERENCES compliance_cases(id) ON DELETE CASCADE,
 reviewer_id BIGINT NOT NULL REFERENCES users(id),note TEXT NOT NULL,created_at TIMESTAMPTZ NOT NULL,
 PRIMARY KEY(case_id,reviewer_id)
);
CREATE INDEX IF NOT EXISTS ix_pg_compliance_case_assignee ON compliance_cases(assigned_to,priority,status);
CREATE INDEX IF NOT EXISTS ix_pg_revocation_pending_lookup ON media_revocation_jobs(upload_id,reason,status);
COMMIT;
