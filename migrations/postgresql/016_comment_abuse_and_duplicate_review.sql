-- Checkpoint 31: human-reviewed advisory records. Never auto-hide or auto-merge.
CREATE TABLE IF NOT EXISTS comment_abuse_flags(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 comment_id BIGINT NOT NULL UNIQUE REFERENCES comments(id) ON DELETE CASCADE,
 signals_json TEXT NOT NULL,
 state VARCHAR(16) NOT NULL DEFAULT 'PENDING' CHECK(state IN ('PENDING','CONFIRMED','DISMISSED')),
 created_at TIMESTAMPTZ NOT NULL, reviewed_at TIMESTAMPTZ, reviewed_by BIGINT REFERENCES users(id)
);
CREATE INDEX IF NOT EXISTS ix_comment_flags_pending ON comment_abuse_flags(state,created_at);
CREATE TABLE IF NOT EXISTS catalog_duplicate_reviews(
 video_a BIGINT NOT NULL REFERENCES videos(id),video_b BIGINT NOT NULL REFERENCES videos(id),
 decision VARCHAR(16) NOT NULL CHECK(decision IN ('DUPLICATE','DISTINCT')),
 reviewed_by BIGINT NOT NULL REFERENCES users(id),reviewed_at TIMESTAMPTZ NOT NULL,
 PRIMARY KEY(video_a,video_b),CHECK(video_a<video_b)
);

COMMIT;
