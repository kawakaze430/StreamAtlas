-- Checkpoint 24 additive MEMBER EXPERIENCE schema, not a production PG cutover.
BEGIN;
ALTER TABLE playlists ADD COLUMN IF NOT EXISTS visibility TEXT NOT NULL DEFAULT 'PRIVATE' CHECK (visibility IN ('PRIVATE','UNLISTED'));
ALTER TABLE user_preferences ADD COLUMN IF NOT EXISTS theme TEXT NOT NULL DEFAULT 'dark';
ALTER TABLE user_preferences ADD COLUMN IF NOT EXISTS locale TEXT NOT NULL DEFAULT 'English';
ALTER TABLE user_preferences ADD COLUMN IF NOT EXISTS save_searches BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE subscriptions ADD COLUMN IF NOT EXISTS notify_mode TEXT NOT NULL DEFAULT 'ALL' CHECK (notify_mode IN ('ALL','HIGHLIGHTS','OFF'));
ALTER TABLE comments ADD COLUMN IF NOT EXISTS parent_id BIGINT REFERENCES comments(id);
ALTER TABLE comments ADD COLUMN IF NOT EXISTS pinned BOOLEAN NOT NULL DEFAULT FALSE;
CREATE TABLE IF NOT EXISTS search_history (
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  query TEXT NOT NULL, searched_at TIMESTAMPTZ NOT NULL,
  PRIMARY KEY (user_id,query));
CREATE INDEX IF NOT EXISTS ix_pg_search_history_recent ON search_history(user_id,searched_at DESC);
CREATE TABLE IF NOT EXISTS comment_reports (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 comment_id BIGINT NOT NULL REFERENCES comments(id) ON DELETE CASCADE,
 reporter_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 reason TEXT NOT NULL,created_at TIMESTAMPTZ NOT NULL,handled_at TIMESTAMPTZ,
 UNIQUE(comment_id,reporter_id));
CREATE INDEX IF NOT EXISTS ix_pg_comment_reports_open ON comment_reports(handled_at,created_at);
COMMIT;
