-- Additive checkpoint 17 moderation/operational schema. Requires 001-003.
-- This file is for a FUTURE PostgreSQL backend; Node runtime remains SQLite.
BEGIN;
CREATE TABLE IF NOT EXISTS content_holds(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 video_id BIGINT NOT NULL REFERENCES videos(id),
 reason TEXT NOT NULL CHECK(reason IN ('CONSENT','AGE','COPYRIGHT','RIGHTS_EXPIRED','OTHER')),
 details TEXT NOT NULL CHECK(char_length(details)>=12),
 opened_by BIGINT NOT NULL REFERENCES users(id),
 opened_at TIMESTAMPTZ NOT NULL,
 closed_by BIGINT REFERENCES users(id),
 closed_at TIMESTAMPTZ,
 closure_note TEXT,
 CONSTRAINT ck_holds_closure CHECK ((closed_at IS NULL AND closed_by IS NULL AND closure_note IS NULL)
    OR (closed_at IS NOT NULL AND closed_by IS NOT NULL AND char_length(closure_note)>=12))
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_content_holds_active ON content_holds(video_id) WHERE closed_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_content_holds_recent ON content_holds(opened_at DESC);
CREATE TABLE IF NOT EXISTS worker_lease(
 name TEXT PRIMARY KEY,owner TEXT NOT NULL,expires_at BIGINT NOT NULL
);
COMMIT;
